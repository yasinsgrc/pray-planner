// Programmatically extracts the license type AND full license text for
// every package that actually ships in the client bundle (design-refresh-v3
// Faz 21 madde 3) — MIT requires the license text + copyright notice to
// accompany distribution, and a bare package-name list does not satisfy
// that. Never hand-transcribe a license here — this reads node_modules
// directly via `license-checker` so the output always matches what's
// actually installed.
//
// Run with: npm run generate:licenses (after any dependency change to the
// packages below, or before a release).
import checker from 'license-checker';
import { readFileSync, writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.join(__dirname, '..');

// Deliberately NOT every production dependency — only the ones that are
// actually imported into client code and end up executing in the browser
// bundle. Server-only (express, pg, web-push, dotenv) and build-time-only
// (vite, typescript, tailwindcss, tsx, playwright-core, sharp) tools never
// ship to an end user's device, so they don't belong on an in-app licenses
// screen — a deliberate, documented choice, not an oversight.
// @capacitor/core, @capacitor/local-notifications, @capacitor/preferences
// added design-refresh-v3 Faz 23 — all three are `import`ed directly by
// client TS (platform.ts, nativeNotifications.ts, widgetStorage.ts) and
// genuinely ship in the web/webview bundle (confirmed: adding platform.ts's
// @capacitor/core import measurably grew dist/assets/index-*.js, and
// installing @capacitor/local-notifications produced its own web.ts
// chunk). @capacitor/android is deliberately NOT here — it's a native
// Java/Kotlin AAR referenced only from Gradle, never imported into any .ts
// file, so it doesn't meet this list's own "client-bundled" criterion.
const CLIENT_BUNDLED_PACKAGE_NAMES = [
  'react',
  'react-dom',
  'adhan',
  'hijri-converter',
  'motion',
  '@phosphor-icons/react',
  '@capacitor/core',
  '@capacitor/local-notifications',
  '@capacitor/preferences',
];

function initLicenseChecker() {
  return new Promise((resolve, reject) => {
    checker.init({ start: PROJECT_ROOT, production: true }, (err, packages) => {
      if (err) reject(err);
      else resolve(packages);
    });
  });
}

async function main() {
  const allPackages = await initLicenseChecker();

  const entries = CLIENT_BUNDLED_PACKAGE_NAMES.map((name) => {
    // license-checker keys entries "name@version" — find the (only)
    // installed version for this name.
    const key = Object.keys(allPackages).find((k) => k.startsWith(`${name}@`));
    if (!key) {
      throw new Error(`generate-licenses: "${name}" not found by license-checker — is it still a dependency?`);
    }
    const info = allPackages[key];
    if (!info.licenseFile) {
      throw new Error(`generate-licenses: no licenseFile found for "${key}" — cannot ship without the actual text.`);
    }
    const version = key.slice(name.length + 1);
    const licenseText = readFileSync(info.licenseFile, 'utf8').trim();
    return { name, version, license: info.licenses ?? 'UNKNOWN', licenseText };
  });

  const output = `// AUTO-GENERATED by scripts/generate-licenses.mjs — do not edit by hand.
// Regenerate with: npm run generate:licenses
// design-refresh-v3 Faz 21 madde 3.

export interface GeneratedLicenseEntry {
  name: string;
  version: string;
  license: string;
  licenseText: string;
}

export const GENERATED_LICENSES: GeneratedLicenseEntry[] = ${JSON.stringify(entries, null, 2)};
`;

  const outPath = path.join(PROJECT_ROOT, 'src', 'data', 'licenses.generated.ts');
  writeFileSync(outPath, output, 'utf8');
  console.log(`Wrote ${entries.length} license entries to ${path.relative(PROJECT_ROOT, outPath)}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
